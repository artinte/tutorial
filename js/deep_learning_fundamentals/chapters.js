export function validateCourseData() {
    const errors = [];

    const chapterIds = new Set();
    const sectionIds = new Set();

    for (const item of chapters) {
        if (chapterIds.has(item.id)) {
            errors.push(
                `重复的章节 ID：${item.id}`
            );
        }

        chapterIds.add(item.id);

        if (!item.title) {
            errors.push(
                `章节 ${item.id} 缺少标题`
            );
        }

        if (!Array.isArray(item.sections)) {
            errors.push(
                `章节 ${item.id} 缺少 sections 数组`
            );

            continue;
        }

        for (const section of item.sections) {
            if (sectionIds.has(section.id)) {
                errors.push(
                    `重复的小节 ID：${section.id}`
                );
            }

            sectionIds.add(section.id);

            if (!section.title) {
                errors.push(
                    `小节 ${section.id} 缺少标题`
                );
            }

            if (!Array.isArray(section.content)) {
                errors.push(
                    `小节 ${section.id} 缺少 content 数组`
                );
            }
        }
    }

    return {
        valid: errors.length === 0,
        chapterCount: chapters.length,
        sectionCount: chapters.reduce(
            (sum, item) =>
                sum + item.sections.length,
            0
        ),
        errors
    };
}