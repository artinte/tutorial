function lesson(
    id,
    page,
    title,
    intro,
    paragraphs,
    options = {}
) {
    const content = [];

    for (const paragraph of paragraphs || []) {
        content.push({
            type: "paragraph",
            text: paragraph
        });
    }

    if (options.heading) {
        content.push({
            type: "heading",
            text: options.heading
        });
    }

    if (options.extraParagraphs) {
        for (const paragraph of options.extraParagraphs) {
            content.push({
                type: "paragraph",
                text: paragraph
            });
        }
    }

    if (options.formula) {
        content.push({
            type: "formula",
            text: options.formula
        });
    }

    if (options.note) {
        content.push({
            type: "note",
            title: options.note.title,
            text: options.note.text,
            variant: options.note.variant || ""
        });
    }

    if (options.concepts) {
        content.push({
            type: "concepts",
            items: options.concepts
        });
    }

    if (options.code) {
        content.push({
            type: "code",
            language: options.code.language || "python",
            code: options.code.code
        });
    }

    if (options.practice) {
        content.push({
            type: "practice",
            title: options.practice.title,
            text: options.practice.text,
            tasks: options.practice.tasks || []
        });
    }

    if (options.misconceptions) {
        content.push({
            type: "callout",
            title: "常见误区",
            text: options.misconceptions,
            variant: "orange"
        });
    }

    if (options.checklist) {
        content.push({
            type: "checklist",
            items: options.checklist
        });
    }

    if (options.questions) {
        content.push({
            type: "thinking",
            items: options.questions
        });
    }

    return {
        id,
        page,
        title,
        intro,
        keywords: options.keywords || [],
        content
    };
}


